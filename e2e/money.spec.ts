import { test, expect, open } from './fixtures'

test.describe('money', () => {
  test('a trip\'s total, paid against planned, by category, and every cost', async ({ page }) => {
    await open(page, '/trip/par?tab=money')
    const money = page.getByRole('region', { name: 'money' })
    await expect(money).toContainText('€680')
    await expect(money).toContainText('paid €480')
    await expect(money).toContainText('planned €200')
    await expect(page.getByRole('region', { name: 'by category' })).toContainText(/food & drink\s*€200/)
    await expect(page.getByRole('region', { name: 'all costs' }).getByRole('button', { name: /hotel marais/ })).toContainText('paid by maya')
  })

  test('settle up says who owes who across the whole trip, and a repayment squares it', async ({ page }) => {
    await open(page, '/trip/par?tab=money')
    const settle = page.getByRole('region', { name: 'settle up' })
    await expect(settle).toContainText('euro summer · with side trips')
    await expect(settle).toContainText(/maya owes you €[\d,.]+/)
    await settle.getByRole('button', { name: /paid back: maya owes you/ }).click()
    await page.getByRole('button', { name: 'confirm repayment' }).click()
    await expect(settle).toContainText('settled')
    // the repayment is written on the top trip
    await open(page, '/trip/eu?tab=money')
    await expect(page.getByRole('region', { name: 'all costs' })).toContainText('maya paid you back')
  })

  test('the money switch shows the parent alone or with its side trips', async ({ page }) => {
    await open(page, '/trip/eu?tab=money')
    const money = page.getByRole('region', { name: 'money' })
    await expect(page.getByRole('region', { name: 'by trip' })).toContainText('paris')
    await page.getByRole('button', { name: 'this trip' }).click()
    await expect(page.getByRole('region', { name: 'by trip' })).toBeHidden()
    await expect(money).toContainText('€3,466')
    await page.getByRole('button', { name: 'with side trips' }).click()
    await expect(money).toContainText('€5,106')
  })

  test('a budget line shows what is left', async ({ page }) => {
    await open(page, '/trip/eu?tab=money')
    await expect(page.getByRole('region', { name: 'money' })).toContainText('of €6,000 · €894 left')
  })

  test('the + adds a cost: amount, who paid, the split; it shows up in the list and the settle-up', async ({ page }) => {
    await open(page, '/trip/par?tab=money')
    await page.getByRole('button', { name: 'add', exact: true }).click()
    await page.getByRole('dialog', { name: 'add' }).getByRole('button', { name: 'cost', exact: true }).click()
    const form = page.getByRole('dialog', { name: 'new cost' })
    await form.getByRole('textbox', { name: 'amount' }).fill('60')
    await form.getByRole('switch', { name: 'paid already' }).click()
    await form.getByRole('group', { name: 'paid by' }).getByRole('button', { name: 'shanice' }).click()
    await form.getByRole('textbox', { name: 'name' }).fill('metro passes')
    await form.getByLabel('category').selectOption('transport')
    await form.getByRole('button', { name: 'save' }).click()
    await expect(form).toBeHidden()
    await expect(page.getByRole('region', { name: 'all costs' })).toContainText('metro passes')
    await expect(page.getByRole('region', { name: 'money' })).toContainText('€740')
    await expect(page.getByRole('region', { name: 'settle up' })).toContainText(/maya owes you €1,492/)
  })

  test('a cost that is only for one person shifts the balance their way', async ({ page }) => {
    await open(page, '/trip/par?tab=money')
    await page.getByRole('button', { name: 'add', exact: true }).click()
    await page.getByRole('dialog', { name: 'add' }).getByRole('button', { name: 'cost', exact: true }).click()
    const form = page.getByRole('dialog', { name: 'new cost' })
    await form.getByRole('textbox', { name: 'amount' }).fill('100')
    await form.getByRole('switch', { name: 'paid already' }).click()
    await form.getByRole('group', { name: 'paid by' }).getByRole('button', { name: 'shanice' }).click()
    await form.getByRole('group', { name: 'split' }).getByRole('button', { name: 'some people' }).click()
    await form.getByRole('button', { name: 'for maya' }).click()
    await form.getByRole('textbox', { name: 'name' }).fill('her museum pass')
    await form.getByRole('button', { name: 'save' }).click()
    await expect(page.getByRole('region', { name: 'settle up' })).toContainText(/maya owes you €1,562/)
  })

  test('a booking\'s cost is changed from its card: who paid, and the settle-up follows', async ({ page }) => {
    await open(page, '/trip/par?tab=money')
    await page.getByRole('region', { name: 'all costs' }).getByRole('button', { name: /hotel marais/ }).click()
    const card = page.getByRole('dialog', { name: 'hotel marais' })
    const money = card.getByRole('region', { name: 'money' })
    await expect(money).toContainText('€480 · paid by maya · split evenly')
    await money.getByRole('button', { name: /paid by maya/ }).click()
    const form = page.getByRole('dialog', { name: 'edit cost' })
    await form.getByRole('group', { name: 'paid by' }).getByRole('button', { name: 'shanice' }).click()
    await form.getByRole('button', { name: 'save' }).click()
    await expect(money).toContainText('€480 · paid by shanice · split evenly')
    await card.getByRole('button', { name: 'close' }).click()
    await expect(page.getByRole('region', { name: 'settle up' })).toContainText(/maya owes you €1,942/)
  })

  test('a booking can carry a second cost', async ({ page }) => {
    await open(page, '/trip/par?tab=money')
    await page.getByRole('region', { name: 'all costs' }).getByRole('button', { name: /hotel marais/ }).click()
    const card = page.getByRole('dialog', { name: 'hotel marais' })
    await card.getByRole('button', { name: 'add a cost →' }).click()
    const form = page.getByRole('dialog', { name: 'new cost' })
    await expect(form.getByRole('textbox', { name: 'name' })).toHaveValue('hotel marais')
    await form.getByRole('textbox', { name: 'name' }).fill('city tax')
    await form.getByRole('textbox', { name: 'amount' }).fill('12')
    await form.getByRole('button', { name: 'save' }).click()
    const money = card.getByRole('region', { name: 'money' })
    await expect(money.getByRole('button')).toHaveCount(2)
    await expect(money).toContainText('city tax')
    await card.getByRole('button', { name: 'close' }).click()
    await expect(page.getByRole('region', { name: 'money' })).toContainText('€692')
  })

  test('other currencies convert at ecb rates, and the display currency can change', async ({ page }) => {
    await open(page, '/trip/jp?tab=money')
    const money = page.getByRole('region', { name: 'money' })
    await expect(money).toContainText(/jpy 59,600/i)
    await money.getByRole('combobox', { name: 'show in' }).selectOption('EUR')
    await expect(money).toContainText(/€\d{3}/)
  })
})
