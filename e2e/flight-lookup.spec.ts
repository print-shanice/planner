import { test, expect, open } from './fixtures'

test('choose a dated departure, save it, and reopen its local times', async ({ page }) => {
  await open(page, '/trip/par?day=2027-02-19')
  await page.getByRole('button', { name: 'add', exact: true }).click()
  await page.getByRole('dialog', { name: /^add/ }).getByRole('button', { name: 'journey', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'new journey' })
  await form.getByRole('button', { name: 'flight', exact: true }).click()
  const lookup = form.getByRole('group', { name: 'flight lookup' })
  await expect(lookup.getByLabel('depart', { exact: true })).toHaveValue('2027-02-19')
  await lookup.getByLabel('flight number').fill('XX 456')
  const layout = await lookup.evaluate((el) => {
    const fields = [...el.querySelectorAll('.field')].map((field) => field.getBoundingClientRect())
    const button = el.querySelector('button.btn')!.getBoundingClientRect()
    return { bottoms: [...fields.map((field) => field.bottom), button.bottom], overflow: el.scrollWidth - el.clientWidth }
  })
  expect(Math.max(...layout.bottoms) - Math.min(...layout.bottoms)).toBeLessThanOrEqual(1.5)
  expect(layout.overflow).toBeLessThanOrEqual(1)
  await lookup.getByRole('button', { name: 'look up', exact: true }).click()
  const choices = form.getByRole('group', { name: 'choose a departure' })
  await expect(choices.getByRole('button')).toHaveCount(3)
  await expect(form.getByRole('button', { name: 'clear from', exact: true })).toHaveCount(0)
  await expect(choices).toContainText('times are local to each airport')
  await choices.getByRole('button', { name: /18:30/ }).focus()
  await page.screenshot({ path: test.info().outputPath('departure-choices.png'), animations: 'disabled' })
  await page.keyboard.press('Enter')
  await expect(choices).toHaveCount(0)
  await expect(form.getByLabel('depart time', { exact: true })).toHaveValue('18:30')
  await expect(form.getByLabel('arrive', { exact: true })).toHaveValue('2027-02-20')
  await expect(form.getByLabel('arrive time', { exact: true })).toHaveValue('00:10')
  await form.getByRole('button', { name: 'save', exact: true }).click()
  await expect(form).toBeHidden()
  const line = page.getByRole('region', { name: 'friday 19 february' }).locator('[data-line]').filter({ hasText: 'XX 456' })
  await expect(line).toContainText('18:30')
  await expect(line).toContainText('lands 00:10')
  await line.locator('.itin-main').click()
  await page.getByRole('dialog').getByRole('button', { name: 'edit', exact: true }).click()
  await expect(page.getByLabel('depart', { exact: true })).toHaveValue('2027-02-19')
  await expect(page.getByLabel('depart time', { exact: true })).toHaveValue('18:30')
  await expect(page.getByLabel('arrive', { exact: true })).toHaveValue('2027-02-20')
})

test('changing the date discards choices and one match still fills the flight directly', async ({ page }) => {
  await open(page, '/trip/par?day=2027-02-19')
  await page.getByRole('button', { name: 'add', exact: true }).click()
  await page.getByRole('dialog', { name: /^add/ }).getByRole('button', { name: 'journey', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'new journey' })
  await form.getByRole('button', { name: 'flight', exact: true }).click()
  const lookup = form.getByRole('group', { name: 'flight lookup' })
  await lookup.getByLabel('flight number').fill('XX 456')
  await lookup.getByRole('button', { name: 'look up', exact: true }).click()
  await expect(form.getByRole('group', { name: 'choose a departure' })).toBeVisible()
  await lookup.getByRole('button', { name: /choose depart/ }).click()
  await page.getByRole('dialog', { name: 'depart', exact: true }).getByRole('button', { name: 'sat 20 feb', exact: true }).click()
  await expect(form.getByRole('group', { name: 'choose a departure' })).toHaveCount(0)
  await lookup.getByLabel('flight number').fill('XX 123')
  await lookup.getByRole('button', { name: 'look up', exact: true }).click()
  await expect(form.getByLabel('depart time', { exact: true })).toHaveValue('09:00')
  await expect(form.getByLabel('depart', { exact: true })).toHaveValue('2027-02-20')
  await expect(form.getByRole('button', { name: 'clear from', exact: true })).toBeVisible()
  const overflow = await form.evaluate((el) => el.scrollWidth - el.clientWidth)
  expect(overflow).toBeLessThanOrEqual(1)
})
