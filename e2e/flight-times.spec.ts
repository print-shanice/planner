import { test, expect, open } from './fixtures'

test('manually typed flight times survive saving and reopening', async ({ page }) => {
  await open(page, '/trip/par?day=2027-02-19')
  await page.getByRole('button', { name: 'add', exact: true }).click()
  await page.getByRole('dialog', { name: /^add/ }).getByRole('button', { name: 'journey', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'new journey' })
  await form.getByRole('button', { name: 'flight', exact: true }).click()
  await form.getByLabel('flight number').fill('KL 1001')
  await form.getByRole('searchbox', { name: 'from', exact: true }).fill('louvre')
  await form.getByRole('button', { name: /Louvre Museum/ }).click()

  const depart = form.getByLabel('depart time', { exact: true })
  await depart.focus()
  await depart.pressSequentially('10:30')
  await expect(depart).toHaveValue('10:30')
  const arrive = form.getByLabel('arrive time', { exact: true })
  await arrive.focus()
  await arrive.pressSequentially('12:45')
  await expect(arrive).toHaveValue('12:45')
  await form.getByRole('button', { name: 'save', exact: true }).click()
  await expect(form).toBeHidden()

  const line = page.locator('[data-line]').filter({ hasText: 'KL 1001' })
  await expect(line).toContainText('10:30')
  await expect(line).toContainText('lands 12:45')
  await line.locator('.itin-main').click()
  const card = page.getByRole('dialog')
  await expect(card).toContainText('depart fri 19 feb · 10:30')
  await expect(card).toContainText('arrive 12:45')
  await card.getByRole('button', { name: 'edit', exact: true }).click()
  await expect(page.getByLabel('depart time', { exact: true })).toHaveValue('10:30')
  await expect(page.getByLabel('arrive time', { exact: true })).toHaveValue('12:45')

  const edit = page.getByRole('dialog')
  await edit.getByLabel('depart time', { exact: true }).fill('6pm')
  await edit.getByLabel('arrive time', { exact: true }).fill('2345')
  // Enter saves while the last time is still focused, before its blur normalizes it.
  await edit.getByLabel('arrive time', { exact: true }).press('Enter')
  await expect(page.getByRole('dialog')).toContainText('depart fri 19 feb · 18:00')
  await expect(page.getByRole('dialog')).toContainText('arrive 23:45')
  await page.getByRole('dialog').getByRole('button', { name: 'close', exact: true }).click()
  await expect(line).toContainText('18:00')
  await expect(line).toContainText('lands 23:45')
})
